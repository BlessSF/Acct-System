<?php
/**
 * SimpleXlsxWriter
 * ------------------------------------------------------------
 * A tiny, dependency-free .xlsx (Excel) writer used to give the
 * "Download" buttons real design: a colored title band per branch,
 * a colored/bold header row, bordered data cells, and a bold
 * totals row — instead of plain, unstyled CSV text.
 *
 * No Composer / PhpSpreadsheet needed — this builds the OOXML
 * zip package by hand using PHP's built-in ZipArchive, so it
 * works on any shared host with the zip extension enabled.
 *
 * USAGE
 * ------------------------------------------------------------
 *   require_once __DIR__ . '/../lib/xlsx_writer.php';
 *
 *   $xlsx = new SimpleXlsxWriter('#0f7b5c'); // branch accent color
 *   $xlsx->title('DemicLab-Jaro Branch — COGS');
 *   $xlsx->subtitle('August 2026');
 *   $xlsx->header(['DATE','BEG.','PURC.','END.','COS','MKTG COST']);
 *   foreach ($rows as $r) {
 *       $xlsx->row([$r['date'], $r['beg'], $r['purc'], $r['end'], $r['cos'], $r['mktg']]);
 *   }
 *   $xlsx->totalRow(['TOTAL', $t['beg'], $t['purc'], $t['end'], $t['cos'], $t['mktg']]);
 *   $xlsx->footer('Generated by SalesHub — ' . date('Y-m-d H:i:s'));
 *   $xlsx->columnWidths([14,12,12,12,12,14]);
 *   $xlsx->output('demiclab_jaro_cogs_2026_08.xlsx');
 * ------------------------------------------------------------
 */
class SimpleXlsxWriter
{
    private array $rows = [];      // ['type' => title|subtitle|header|data|total|footer|blank, 'cells' => [...]]
    private array $colWidths = [];
    private string $accent;        // branch accent color, e.g. '#0f7b5c'
    private int $maxCols = 1;

    public function __construct(string $accentColor = '#0f7b5c')
    {
        $this->accent = ltrim($accentColor, '#');
        if (strlen($this->accent) !== 6) $this->accent = '0F7B5C';
    }

    public function title(string $text): void   { $this->rows[] = ['type' => 'title', 'cells' => [$text]]; }
    public function subtitle(string $text): void { $this->rows[] = ['type' => 'subtitle', 'cells' => [$text]]; }
    public function blank(): void                { $this->rows[] = ['type' => 'blank', 'cells' => []]; }
    public function footer(string $text): void   { $this->rows[] = ['type' => 'footer', 'cells' => [$text]]; }

    public function header(array $cells): void
    {
        $this->maxCols = max($this->maxCols, count($cells));
        $this->rows[] = ['type' => 'header', 'cells' => $cells];
    }

    public function row(array $cells): void
    {
        $this->maxCols = max($this->maxCols, count($cells));
        $this->rows[] = ['type' => 'data', 'cells' => $cells];
    }

    /** A visually distinct sub-header / section label row (bold, tinted band, spans width). */
    public function sectionRow(string $text): void
    {
        $this->rows[] = ['type' => 'section', 'cells' => [$text]];
    }

    public function totalRow(array $cells): void
    {
        $this->maxCols = max($this->maxCols, count($cells));
        $this->rows[] = ['type' => 'total', 'cells' => $cells];
    }

    public function columnWidths(array $widths): void { $this->colWidths = $widths; }

    private static function colLetter(int $i): string
    {
        $letter = '';
        $i++;
        while ($i > 0) {
            $mod = ($i - 1) % 26;
            $letter = chr(65 + $mod) . $letter;
            $i = intdiv($i - 1, 26);
        }
        return $letter;
    }

    private static function isNumeric($v): bool
    {
        if ($v === null || $v === '') return false;
        $clean = str_replace(',', '', (string)$v);
        return is_numeric($clean);
    }

    private static function xmlEscape(string $s): string
    {
        return htmlspecialchars($s, ENT_QUOTES | ENT_XML1, 'UTF-8');
    }

    /**
     * Style index map (built into styles.xml, order matters — must match writeStylesXml()):
     * 0 default | 1 title | 2 subtitle | 3 header | 4 data-text | 5 data-num
     * 6 total-text | 7 total-num | 8 footer | 9 section
     */
    private function styleForCell(string $rowType, bool $numeric): int
    {
        return match ($rowType) {
            'title'    => 1,
            'subtitle' => 2,
            'header'   => 3,
            'total'    => $numeric ? 7 : 6,
            'footer'   => 8,
            'section'  => 9,
            default    => $numeric ? 5 : 4,
        };
    }

    private function buildSheetXml(): string
    {
        $mergeCells = [];
        $xml = '<sheetData>';
        $rIdx = 0;
        foreach ($this->rows as $r) {
            $rIdx++;
            if ($r['type'] === 'blank') { $xml .= "<row r=\"$rIdx\"/>"; continue; }

            $height = in_array($r['type'], ['title'], true) ? ' ht="22" customHeight="1"' : '';
            $xml .= "<row r=\"$rIdx\"$height>";

            if (in_array($r['type'], ['title', 'subtitle', 'footer', 'section'], true)) {
                // Single logical cell merged across the full table width for a clean banner look.
                $span = max(1, $this->maxCols) - 1;
                $endCol = self::colLetter($span);
                if ($span > 0) $mergeCells[] = "A{$rIdx}:{$endCol}{$rIdx}";
                $style = $this->styleForCell($r['type'], false);
                $val = self::xmlEscape((string)($r['cells'][0] ?? ''));
                $xml .= "<c r=\"A{$rIdx}\" t=\"inlineStr\" s=\"{$style}\"><is><t xml:space=\"preserve\">{$val}</t></is></c>";
            } else {
                foreach ($r['cells'] as $ci => $val) {
                    $col = self::colLetter($ci);
                    $numeric = self::isNumeric($val) && $r['type'] !== 'header';
                    $style = $this->styleForCell($r['type'], $numeric);
                    $ref = "{$col}{$rIdx}";
                    if ($numeric) {
                        $num = str_replace(',', '', (string)$val);
                        $xml .= "<c r=\"{$ref}\" s=\"{$style}\"><v>{$num}</v></c>";
                    } else {
                        $val = self::xmlEscape((string)$val);
                        $xml .= "<c r=\"{$ref}\" t=\"inlineStr\" s=\"{$style}\"><is><t xml:space=\"preserve\">{$val}</t></is></c>";
                    }
                }
            }
            $xml .= '</row>';
        }
        $xml .= '</sheetData>';

        if (!empty($mergeCells)) {
            $xml .= '<mergeCells count="' . count($mergeCells) . '">';
            foreach ($mergeCells as $mc) $xml .= "<mergeCell ref=\"{$mc}\"/>";
            $xml .= '</mergeCells>';
        }
        return $xml;
    }

    private function buildColsXml(): string
    {
        if (empty($this->colWidths)) return '';
        $xml = '<cols>';
        foreach ($this->colWidths as $i => $w) {
            $c = $i + 1;
            $xml .= "<col min=\"{$c}\" max=\"{$c}\" width=\"{$w}\" customWidth=\"1\"/>";
        }
        $xml .= '</cols>';
        return $xml;
    }

    private function buildStylesXml(): string
    {
        $accent = $this->accent;
        // Light tint of the accent color, used for section/total row shading.
        $tint = $this->tintColor($accent, 0.88);
        return '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<styleSheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
<numFmts count="1"><numFmt numFmtId="164" formatCode="#,##0.00"/></numFmts>
<fonts count="6">
<font><sz val="10"/><name val="Calibri"/></font>
<font><b/><sz val="14"/><color rgb="FF' . $accent . '"/><name val="Calibri"/></font>
<font><sz val="10"/><color rgb="FF6B7280"/><name val="Calibri"/></font>
<font><b/><sz val="10"/><color rgb="FFFFFFFF"/><name val="Calibri"/></font>
<font><b/><sz val="10"/><color rgb="FF1A1D23"/><name val="Calibri"/></font>
<font><i/><sz val="9"/><color rgb="FF9CA3AF"/><name val="Calibri"/></font>
</fonts>
<fills count="4">
<fill><patternFill patternType="none"/></fill>
<fill><patternFill patternType="gray125"/></fill>
<fill><patternFill patternType="solid"><fgColor rgb="FF' . $accent . '"/><bgColor indexed="64"/></patternFill></fill>
<fill><patternFill patternType="solid"><fgColor rgb="FF' . $tint . '"/><bgColor indexed="64"/></patternFill></fill>
</fills>
<borders count="3">

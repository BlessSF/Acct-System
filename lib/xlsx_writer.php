<border><left/><right/><top style="thin"><color rgb="FF' . $accent . '"/></top><bottom style="double"><color rgb="FF' . $accent . '"/></bottom><diagonal/></border>
</borders>
<cellStyleXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"/></cellStyleXfs>
<cellXfs count="10">
<xf numFmtId="0"  fontId="0" fillId="0" borderId="0" xfId="0"/>
<xf numFmtId="0"  fontId="1" fillId="0" borderId="0" xfId="0" applyFont="1"><alignment vertical="center"/></xf>
<xf numFmtId="0"  fontId="2" fillId="0" borderId="0" xfId="0" applyFont="1"/>
<xf numFmtId="0"  fontId="3" fillId="2" borderId="1" xfId="0" applyFont="1" applyFill="1" applyBorder="1"><alignment vertical="center" horizontal="center"/></xf>
<xf numFmtId="0"  fontId="0" fillId="0" borderId="1" xfId="0" applyBorder="1"/>
<xf numFmtId="164" fontId="0" fillId="0" borderId="1" xfId="0" applyNumberFormat="1" applyBorder="1"><alignment horizontal="right"/></xf>
<xf numFmtId="0"  fontId="4" fillId="3" borderId="2" xfId="0" applyFont="1" applyFill="1" applyBorder="1"/>
<xf numFmtId="164" fontId="4" fillId="3" borderId="2" xfId="0" applyFont="1" applyFill="1" applyNumberFormat="1" applyBorder="1"><alignment horizontal="right"/></xf>
<xf numFmtId="0"  fontId="5" fillId="0" borderId="0" xfId="0" applyFont="1"/>
<xf numFmtId="0"  fontId="4" fillId="3" borderId="0" xfId="0" applyFont="1" applyFill="1"><alignment vertical="center"/></xf>
</cellXfs>
<cellStyles count="1"><cellStyle name="Normal" xfId="0" builtinId="0"/></cellStyles>
</styleSheet>';
    }

    /** Blend a hex color toward white by $amount (0..1) for a light tint fill. */
    private function tintColor(string $hex, float $amount): string
    {
        $r = hexdec(substr($hex, 0, 2));
        $g = hexdec(substr($hex, 2, 2));
        $b = hexdec(substr($hex, 4, 2));
        $r = (int)round($r + (255 - $r) * $amount);
        $g = (int)round($g + (255 - $g) * $amount);
        $b = (int)round($b + (255 - $b) * $amount);
        return strtoupper(sprintf('%02X%02X%02X', $r, $g, $b));
    }

    /**
     * Stream the finished .xlsx to the browser as a download and exit.
     * If $return is true, returns the raw bytes instead of streaming (useful for tests).
     *
     * Builds the zip container by hand (only needs the near-universal zlib
     * extension) instead of requiring the ZipArchive class, which many
     * default PHP installs (including stock XAMPP) ship disabled.
     */
    public function output(string $filename, bool $return = false)
    {
        $files = [];

        $files['[Content_Types].xml'] =
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' .
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">' .
            '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>' .
            '<Default Extension="xml" ContentType="application/xml"/>' .
            '<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>' .
            '<Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>' .
            '<Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>' .
            '</Types>';

        $files['_rels/.rels'] =
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' .
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">' .
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>' .
            '</Relationships>';

        $files['xl/_rels/workbook.xml.rels'] =
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' .
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">' .
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>' .
            '<Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>' .
            '</Relationships>';

        $files['xl/workbook.xml'] =
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' .
            '<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">' .
            '<sheets><sheet name="Sheet1" sheetId="1" r:id="rId1"/></sheets>' .
            '</workbook>';

        $files['xl/styles.xml'] = $this->buildStylesXml();

        $files['xl/worksheets/sheet1.xml'] =
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' .
            '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">' .
            $this->buildColsXml() .
            $this->buildSheetXml() .
            '</worksheet>';

        $bytes = class_exists('ZipArchive')
            ? $this->buildZipWithZipArchive($files)
            : $this->buildZipManually($files);

        if ($return) return $bytes;

        header('Content-Type: application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
        header('Content-Disposition: attachment; filename="' . $filename . '"');
        header('Content-Length: ' . strlen($bytes));
        echo $bytes;
        exit;
    }

    /** @param array<string,string> $files relative path => contents */
    private function buildZipWithZipArchive(array $files): string
    {
        $tmp = tempnam(sys_get_temp_dir(), 'xlsx_');
        $zip = new ZipArchive();
        $zip->open($tmp, ZipArchive::OVERWRITE);
        foreach ($files as $path => $contents) {
            $zip->addFromString($path, $contents);
        }
        $zip->close();
        $bytes = file_get_contents($tmp);
        unlink($tmp);
        return $bytes;
    }

    /**
     * Minimal store/deflate ZIP writer using only zlib's gzdeflate() —
     * no ZipArchive / php-zip extension required. Produces a standard
     * ZIP that Excel, 7-Zip, and Python's zipfile all read fine.
     *
     * @param array<string,string> $files relative path => contents
     */
    private function buildZipManually(array $files): string
    {
        $useDeflate = function_exists('gzdeflate');
        $localParts = [];
        $centralParts = [];
        $offset = 0;

        foreach ($files as $path => $contents) {
            $nameBin = $path;
            $crc = crc32($contents);
            $uncompressedSize = strlen($contents);

            if ($useDeflate) {
                $compressed = gzdeflate($contents, 6);
                $method = 8; // deflate
            } else {
                $compressed = $contents;
                $method = 0; // store
            }
            $compressedSize = strlen($compressed);

            // Local file header
            $localHeader = "PK\x03\x04"
                . pack('v', 20)      // version needed
                . pack('v', 0)       // flags
                . pack('v', $method) // compression method
                . pack('V', 0)       // mod time+date (unused, 0 is valid)
                . pack('V', $crc)
                . pack('V', $compressedSize)
                . pack('V', $uncompressedSize)
                . pack('v', strlen($nameBin))
                . pack('v', 0)       // extra field length
                . $nameBin;

            $localParts[] = $localHeader . $compressed;

            // Central directory header
            $centralHeader = "PK\x01\x02"
                . pack('v', 20)      // version made by
                . pack('v', 20)      // version needed
                . pack('v', 0)       // flags
                . pack('v', $method)
                . pack('V', 0)
                . pack('V', $crc)
                . pack('V', $compressedSize)
                . pack('V', $uncompressedSize)
                . pack('v', strlen($nameBin))
                . pack('v', 0)       // extra field length
                . pack('v', 0)       // comment length
                . pack('v', 0)       // disk number start
                . pack('v', 0)       // internal attrs
                . pack('V', 0)       // external attrs
                . pack('V', $offset) // offset of local header
                . $nameBin;

            $centralParts[] = $centralHeader;
            $offset += strlen($localHeader) + $compressedSize;
        }

        $localBlock = implode('', $localParts);
        $centralBlock = implode('', $centralParts);

        $endRecord = "PK\x05\x06"
            . pack('v', 0)                  // disk number
            . pack('v', 0)                  // disk with central dir
            . pack('v', count($files))      // entries on this disk
            . pack('v', count($files))      // total entries
            . pack('V', strlen($centralBlock))
            . pack('V', strlen($localBlock)) // offset of central dir
            . pack('v', 0);                  // comment length

        return $localBlock . $centralBlock . $endRecord;
    }
}

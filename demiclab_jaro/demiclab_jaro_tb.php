// ── Section definitions ────────────────────────────────────
// ASSETS and EXPENSES now come from demiclab_jaro_acc_titles (managed via
// demiclab_jaro_acc_title.php) instead of a hardcoded list, grouped by section.
// REVENUE rows are manual P&L revenue types, unrelated to account titles.
$acctRows = $pdo->query("SELECT title, section FROM `demiclab_jaro_acc_titles` ORDER BY sort_order ASC, title ASC")->fetchAll(PDO::FETCH_ASSOC);
$ASSETS = []; $EXPENSES = [];
foreach ($acctRows as $a) {
    if ($a['section'] === 'assets') $ASSETS[] = $a['title'];
    elseif ($a['section'] === 'expenses') $EXPENSES[] = $a['title'];
}


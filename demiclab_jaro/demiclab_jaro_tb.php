        SELECT MONTH(entry_date) as mo, account_title, SUM(net_of_vat) as total
        FROM demiclab_jaro_disbursement
        WHERE YEAR(entry_date) = ? AND account_title != ''
        GROUP BY MONTH(entry_date), account_title
    ");
    $stmt->execute([$YEAR]);
    $data = [];
    foreach ($stmt->fetchAll() as $r) $data[$r['account_title']][$r['mo']] = (float)$r['total'];

    // Include any account_title used in disbursement that's no longer in the
    // masterlist (renamed/deleted), so historical totals aren't dropped.
    $csvKnown = array_merge($ASSETS, $EXPENSES);
    foreach (array_keys($data) as $t) {
        if (!in_array($t, $csvKnown, true)) $EXPENSES[] = $t;
    }

    require_once __DIR__ . '/../lib/xlsx_writer.php';
    require_once __DIR__ . '/../lib/branch_colors.php';

    $xlsx = new SimpleXlsxWriter(branchAccentColor('DemicLab-Jaro'));
    $xlsx->title('MERITONI CORP');
    $xlsx->subtitle('DemicLab-Jaro Trial Balance');
    $xlsx->subtitle('Year ' . $YEAR . ' · Generated ' . date('F d, Y H:i:s'));
    $xlsx->blank();
    $xlsx->header(array_merge(['ACCOUNT TITLE','TOTAL'], $MONTHS));

    foreach (['ASSETS' => $ASSETS, 'REVENUE' => $REVENUE, 'EXPENSES' => $EXPENSES] as $sec => $rows) {
        $xlsx->sectionRow($sec);
        foreach ($rows as $label) {
            $rowTotal = 0; $mVals = [];
            for ($m = 1; $m <= 12; $m++) {
                $v = $data[$label][$m] ?? 0;
                $rowTotal += $v;
                $mVals[] = $v ? number_format($v,2,'.','') : '-';
            }
            $xlsx->row(array_merge([$label, $rowTotal ? number_format($rowTotal,2,'.','') : '-'], $mVals));
        }
    }
    $xlsx->footer('Generated by SalesHub — ' . date('Y-m-d H:i:s'));
    $xlsx->columnWidths(array_merge([28,13], array_fill(0,12,9)));
    $xlsx->output('DemicLab-Jaro_TB_' . $YEAR . '.xlsx');
    exit;
}


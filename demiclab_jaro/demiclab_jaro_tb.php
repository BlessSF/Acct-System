    'Vatable Sales (VAT Inclusive)',
    'Exempt Sales',
    'Other Income',
];

$MONTHS = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];

// ── CSV Export ────────────────────────────────────────────

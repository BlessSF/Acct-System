// ============================================================
//  demiclab_jaro_sum.php — DemicLab-Jaro Sum / Checking View
//  Mirrors the Excel "Checking" tab format:
//  ASSETS + EXPENSES rows × Jan–Dec months with TOTAL column
//  Data pulled live from demiclab_jaro_disbursement
// ============================================================
require_once '../config.php';
require_once '../auth.php';
requireLogin();

if (isBranch() && currentBranch() !== 'DemicLab-Jaro') {
    header('Location: ../dashboard.php'); exit;
}

$pdo  = getPDO();
// Safety guard — demiclab_jaro_acc_titles is normally created by
// demiclab_jaro_disbursement.php / demiclab_jaro_acc_title.php, but ensure it exists
// here too in case this page is loaded first.
$pdo->exec("CREATE TABLE IF NOT EXISTS `demiclab_jaro_acc_titles` (
    `id`          int(11) NOT NULL AUTO_INCREMENT,
    `title`       varchar(255) NOT NULL,
    `section`     enum('assets','expenses','other') NOT NULL DEFAULT 'expenses',
    `sort_order`  int(6) NOT NULL DEFAULT 0,
    `saved_by`    varchar(100) DEFAULT NULL,
    `created_at`  timestamp NOT NULL DEFAULT current_timestamp(),
    PRIMARY KEY (`id`),
    UNIQUE KEY `uniq_title` (`title`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci");
$YEAR = (int)($_GET['year'] ?? date('Y'));

// ── CSV Export ────────────────────────────────────────────
if (isset($_GET['export_csv'])) {
    $expRows = $pdo->prepare("
        SELECT MONTH(entry_date) as mo, account_title, SUM(net_of_vat) as total
        FROM demiclab_jaro_disbursement
        WHERE YEAR(entry_date) = ? AND account_title != ''
        GROUP BY MONTH(entry_date), account_title
    ");
    $expRows->execute([$YEAR]);
    $expenses = [];
    foreach ($expRows->fetchAll() as $r) {
        $expenses[$r['account_title']][$r['mo']] = (float)$r['total'];
    }

    $MONTHS_FULL = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];

    // Account title rows now come from demiclab_jaro_acc_titles (managed via
    // demiclab_jaro_acc_title.php) instead of a hardcoded list, grouped by section.
    // Any account_title found in disbursement data that's no longer in the
    // masterlist (renamed/deleted) is still included under Expenses so
    // historical totals are never silently dropped.
    $acctRows = $pdo->query("SELECT title, section FROM `demiclab_jaro_acc_titles` ORDER BY sort_order ASC, title ASC")->fetchAll(PDO::FETCH_ASSOC);
    $assetsList = []; $expenseList = [];
    foreach ($acctRows as $a) {
        if ($a['section'] === 'assets') $assetsList[] = $a['title'];
        elseif ($a['section'] === 'expenses') $expenseList[] = $a['title'];
    }
    $knownTitles = array_merge($assetsList, $expenseList);
    foreach (array_keys($expenses) as $t) {
        if (!in_array($t, $knownTitles, true)) $expenseList[] = $t;
    }

    $sections = [
        'ASSETS'   => $assetsList,
        'EXPENSES' => $expenseList,
    ];

    require_once __DIR__ . '/../lib/xlsx_writer.php';
    require_once __DIR__ . '/../lib/branch_colors.php';

    $xlsx = new SimpleXlsxWriter(branchAccentColor('DemicLab-Jaro'));
    $xlsx->title('MERITONI CORP');
    $xlsx->subtitle('DemicLab-Jaro — Sum / Checking');
    $xlsx->subtitle('Year ' . $YEAR . ' · Generated ' . date('F d, Y H:i:s'));
    $xlsx->blank();
    $xlsx->header(array_merge(['ACCOUNT TITLE','TOTAL'], $MONTHS_FULL));

    foreach ($sections as $sec => $rows) {
        $xlsx->sectionRow($sec);
        foreach ($rows as $label) {
            $mVals = [];
            $total = 0;
            for ($m = 1; $m <= 12; $m++) {
                $v = $expenses[$label][$m] ?? 0;
                $total += $v;
                $mVals[] = $v ? number_format($v,2,'.','') : '-';
            }
            $xlsx->row(array_merge([$label, $total ? number_format($total,2,'.','') : '-'], $mVals));
        }
    }
    $xlsx->footer('Generated by SalesHub — ' . date('Y-m-d H:i:s'));
    $xlsx->columnWidths(array_merge([28,13], array_fill(0,12,9)));
    $xlsx->output('DemicLab-Jaro_Sum_' . $YEAR . '.xlsx');
    exit;
}

// ── Load disbursement data ─────────────────────────────────
$expRows = $pdo->prepare("
    SELECT MONTH(entry_date) as mo, account_title, SUM(net_of_vat) as total
    FROM demiclab_jaro_disbursement
    WHERE YEAR(entry_date) = ? AND account_title != ''
    GROUP BY MONTH(entry_date), account_title
    ORDER BY account_title, mo
");
$expRows->execute([$YEAR]);
$expenses = [];
foreach ($expRows->fetchAll() as $r) {
    $expenses[$r['account_title']][$r['mo']] = (float)$r['total'];
}

$MONTHS = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];

// Account title rows now come from demiclab_jaro_acc_titles (managed via
// demiclab_jaro_acc_title.php) instead of a hardcoded list, grouped by section.
// Any account_title found in disbursement data that's no longer in the
// masterlist (renamed/deleted) is still included under Expenses so
// historical totals are never silently dropped.
$acctRows = $pdo->query("SELECT title, section FROM `demiclab_jaro_acc_titles` ORDER BY sort_order ASC, title ASC")->fetchAll(PDO::FETCH_ASSOC);

<?php
// ============================================================
//  stella_sum.php — Stella Sum / Checking View
//  Mirrors the Excel "Checking" tab format:
//  ASSETS + EXPENSES rows × Jan–Dec months with TOTAL column
//  Data pulled live from stella_disbursement
// ============================================================
require_once '../config.php';
require_once '../auth.php';
requireLogin();

if (isBranch() && currentBranch() !== 'Stella') {
    header('Location: ../dashboard.php'); exit;
}

$pdo  = getPDO();
// Safety guard — stella_acc_titles is normally created by
// stella_disbursement.php / stella_acc_title.php, but ensure it exists
// here too in case this page is loaded first.
$pdo->exec("CREATE TABLE IF NOT EXISTS `stella_acc_titles` (
    `id`          int(11) NOT NULL AUTO_INCREMENT,
    `title`       varchar(255) NOT NULL,
    `section`     enum('assets','expenses','other') NOT NULL DEFAULT 'expenses',
    `sort_order`  int(6) NOT NULL DEFAULT 0,
    `saved_by`    varchar(100) DEFAULT NULL,
    `created_at`  timestamp NOT NULL DEFAULT current_timestamp(),
    PRIMARY KEY (`id`),
    UNIQUE KEY `uniq_title` (`title`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci");
$YEAR = (int)($_GET['year'] ?? date('Y'));

// ── CSV Export ────────────────────────────────────────────
if (isset($_GET['export_csv'])) {
    $expRows = $pdo->prepare("
        SELECT MONTH(entry_date) as mo, account_title, SUM(net_of_vat) as total
        FROM stella_disbursement
        WHERE YEAR(entry_date) = ? AND account_title != ''
        GROUP BY MONTH(entry_date), account_title
    ");
    $expRows->execute([$YEAR]);
    $expenses = [];
    foreach ($expRows->fetchAll() as $r) {
        $expenses[$r['account_title']][$r['mo']] = (float)$r['total'];
    }

    $MONTHS_FULL = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];

    // Account title rows now come from stella_acc_titles (managed via
    // stella_acc_title.php) instead of a hardcoded list, grouped by section.
    // Any account_title found in disbursement data that's no longer in the
    // masterlist (renamed/deleted) is still included under Expenses so
    // historical totals are never silently dropped.
    $acctRows = $pdo->query("SELECT title, section FROM `stella_acc_titles` ORDER BY sort_order ASC, title ASC")->fetchAll(PDO::FETCH_ASSOC);
    $assetsList = []; $expenseList = [];
    foreach ($acctRows as $a) {
        if ($a['section'] === 'assets') $assetsList[] = $a['title'];
        elseif ($a['section'] === 'expenses') $expenseList[] = $a['title'];
    }
    $knownTitles = array_merge($assetsList, $expenseList);
    foreach (array_keys($expenses) as $t) {
        if (!in_array($t, $knownTitles, true)) $expenseList[] = $t;
    }

    $sections = [
        'ASSETS'   => $assetsList,
        'EXPENSES' => $expenseList,
    ];

    require_once __DIR__ . '/../lib/xlsx_writer.php';
    require_once __DIR__ . '/../lib/branch_colors.php';

    $xlsx = new SimpleXlsxWriter(branchAccentColor('Stella'));
    $xlsx->title('MERITONI CORP');
    $xlsx->subtitle('Stella — Sum / Checking');
    $xlsx->subtitle('Year ' . $YEAR . ' · Generated ' . date('F d, Y H:i:s'));
    $xlsx->blank();
    $xlsx->header(array_merge(['ACCOUNT TITLE','TOTAL'], $MONTHS_FULL));

    foreach ($sections as $sec => $rows) {
        $xlsx->sectionRow($sec);
        foreach ($rows as $label) {
            $mVals = [];
            $total = 0;
            for ($m = 1; $m <= 12; $m++) {
                $v = $expenses[$label][$m] ?? 0;
                $total += $v;
                $mVals[] = $v ? number_format($v,2,'.','') : '-';
            }
            $xlsx->row(array_merge([$label, $total ? number_format($total,2,'.','') : '-'], $mVals));
        }
    }
    $xlsx->footer('Generated by SalesHub — ' . date('Y-m-d H:i:s'));
    $xlsx->columnWidths(array_merge([28,13], array_fill(0,12,9)));
    $xlsx->output('Stella_Sum_' . $YEAR . '.xlsx');
    exit;
}

// ── Load disbursement data ─────────────────────────────────
$expRows = $pdo->prepare("
    SELECT MONTH(entry_date) as mo, account_title, SUM(net_of_vat) as total
    FROM stella_disbursement
    WHERE YEAR(entry_date) = ? AND account_title != ''
    GROUP BY MONTH(entry_date), account_title
    ORDER BY account_title, mo
");
$expRows->execute([$YEAR]);
$expenses = [];
foreach ($expRows->fetchAll() as $r) {
    $expenses[$r['account_title']][$r['mo']] = (float)$r['total'];
}

$MONTHS = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];

// Account title rows now come from stella_acc_titles (managed via
// stella_acc_title.php) instead of a hardcoded list, grouped by section.
// Any account_title found in disbursement data that's no longer in the
// masterlist (renamed/deleted) is still included under Expenses so
// historical totals are never silently dropped.
$acctRows = $pdo->query("SELECT title, section FROM `stella_acc_titles` ORDER BY sort_order ASC, title ASC")->fetchAll(PDO::FETCH_ASSOC);
$ASSETS = []; $EXPENSE_ROWS = [];
foreach ($acctRows as $a) {
    if ($a['section'] === 'assets') $ASSETS[] = $a['title'];
    elseif ($a['section'] === 'expenses') $EXPENSE_ROWS[] = $a['title'];
}
$knownTitles = array_merge($ASSETS, $EXPENSE_ROWS);
foreach (array_keys($expenses) as $t) {
    if (!in_array($t, $knownTitles, true)) $EXPENSE_ROWS[] = $t;
}

$pageTitle  = 'Stella Sum';
$activePage = 'stella_profit_loss'; // keep P&L active in sidebar
$bodyClass = 'sp-stella_sum';
include '../layout.php';
?>

<link rel="stylesheet" href="<?= BASE_URL ?>/assets/css/style.css?v=<?= @filemtime(__DIR__ . '/../assets/css/style.css') ?: time() ?>">

<!-- Page header -->
<div class="section-header">
  <div>
    <div class="section-title">Stella <span>Sum</span></div>
    <div class="section-subtitle">MERITONI CORP · Checking view — Assets &amp; Expenses by month · Data from Disbursement</div>
  </div>
</div>

<!-- Controls -->
<div class="sum-controls">
  <a href="?year=<?= $YEAR-1 ?>" class="yr-btn">← <?= $YEAR-1 ?></a>
  <span class="yr-current"><?= $YEAR ?></span>
  <a href="?year=<?= $YEAR+1 ?>" class="yr-btn"><?= $YEAR+1 ?> →</a>
  <a href="stella_disbursement.php" class="btn-action">📒 Go to Disbursement</a>
  <a href="stella_acc_title.php" class="sx-2 btn-action" >🏷 Account Titles</a>
  <a href="stella_profit_loss.php?year=<?= $YEAR ?>" class="btn-action btn-pl">📊 Profit & Loss</a>
  <a href="?year=<?= $YEAR ?>&export_csv=1" class="btn-action">⬇ Export XLSX</a>
</div>

<!-- Table -->
<div class="sum-wrap">
<table class="sum-table" id="sumt">
  <thead>
    <tr>
      <th class="th-label">ACCOUNT TITLE</th>
      <th class="th-sub">ACCOUNT TITLE</th>
      <th class="th-total">TOTAL</th>
      <?php foreach ($MONTHS as $m): ?>
      <th class="th-mo"><?= $m ?></th>
      <?php endforeach; ?>
    </tr>
  </thead>
  <tbody>

    <!-- ── ASSETS ─────────────────────────────────────── -->
    <tr class="sum-sec-row"><td colspan="15">ASSETS</td></tr>
    <?php foreach ($ASSETS as $label):
      $rowTotal = 0; $mVals = [];
      for ($m = 1; $m <= 12; $m++) {
        $v = $expenses[$label][$m] ?? 0;
        $rowTotal += $v; $mVals[] = $v;
      }
    ?>
    <tr>
      <td class="td-label"><?= htmlspecialchars($label) ?></td>
      <td class="td-sub"><?= htmlspecialchars($label) ?></td>
      <td class="td-total"><?= $rowTotal ? number_format($rowTotal,2) : '<span class="td-zero">-</span>' ?></td>
      <?php foreach ($mVals as $v): ?>
      <td class="<?= !$v ? 'td-zero' : '' ?>"><?= $v ? number_format($v,2) : '-' ?></td>
      <?php endforeach; ?>
    </tr>
    <?php endforeach; ?>

    <!-- Blank spacer -->
    <tr><td colspan="15" class="sx-1"></td></tr>

    <!-- ── EXPENSES ───────────────────────────────────── -->
    <tr class="sum-sec-row"><td colspan="15">EXPENSES</td></tr>
    <?php
    $grandTotals = array_fill(0, 12, 0);
    $grandTotal  = 0;
    foreach ($EXPENSE_ROWS as $label):
      $rowTotal = 0; $mVals = [];
      for ($m = 1; $m <= 12; $m++) {
        $v = $expenses[$label][$m] ?? 0;
        $rowTotal += $v; $mVals[] = $v;
        $grandTotals[$m-1] += $v;
      }
      $grandTotal += $rowTotal;
    ?>
    <tr>
      <td class="td-label"><?= htmlspecialchars($label) ?></td>
      <td class="td-sub"><?= htmlspecialchars($label) ?></td>
      <td class="td-total"><?= $rowTotal ? number_format($rowTotal,2) : '<span class="td-zero">-</span>' ?></td>
      <?php foreach ($mVals as $v): ?>
      <td class="<?= !$v ? 'td-zero' : '' ?>"><?= $v ? number_format($v,2) : '-' ?></td>
      <?php endforeach; ?>
    </tr>
    <?php endforeach; ?>

  </tbody>
  <tfoot>
    <tr>
      <td class="td-label" colspan="2">TOTAL EXPENSES</td>
      <td><?= $grandTotal ? number_format($grandTotal,2) : '-' ?></td>
      <?php foreach ($grandTotals as $t): ?>
      <td><?= $t ? number_format($t,2) : '-' ?></td>
      <?php endforeach; ?>
    </tr>
  </tfoot>
</table>
</div>

  </div></div>
</body>
</html>